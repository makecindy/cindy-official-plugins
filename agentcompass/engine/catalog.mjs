export function pyRepr(text) {
  const quote = text.includes("'") && !text.includes('"') ? '"' : "'";
  let out = quote;
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === quote || ch === "\\") out += `\\${ch}`;
    else if (ch === "\t") out += "\\t";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (code < 0x20 || code === 0x7f) out += `\\x${hex(code, 2)}`;
    else if (code < 0x7f || (ch !== " " && !PY_UNPRINTABLE.test(ch))) out += ch;
    else if (code <= 0xff) out += `\\x${hex(code, 2)}`;
    else if (code <= 0xffff) out += `\\u${hex(code, 4)}`;
    else out += `\\U${hex(code, 8)}`;
  }
  return out + quote;
}

/**
 * A value as the engine's message shows it (`{raw!r}`): a string, a boolean, `null` and a number of a JSON request as Python's
 * `repr()` of the value Python decodes; anything else without throwing (a bigint, a circular or prototype-less object).
 */
function shownValue(raw) {
  if (raw === undefined || raw === null) return "None";
  if (typeof raw === "string") return pyRepr(raw);
  if (typeof raw === "boolean") return raw ? "True" : "False";
  if (typeof raw === "bigint") return `${raw}`;
  if (typeof raw === "number") return Number.isNaN(raw) ? "nan" : Number.isFinite(raw) ? `${raw}` : raw > 0 ? "inf" : "-inf";
  if (Array.isArray(raw) && raw.length === 0) return "[]";
  try {
    if (Object.getPrototypeOf(raw) === Object.prototype && Object.keys(raw).length === 0) return "{}";
    const text = JSON.stringify(raw);
    if (typeof text === "string") return text;
  } catch {
    // shown by its type below
  }
  return Object.prototype.toString.call(raw);
}

/**
 * Why a model pin is malformed, else `null` (`model_resolution.model_pin_problem`): not a string, a string Python's `strip()` leaves
 * empty, an `auto:` id without its account and harness, or an empty part around a `/` or a `:` (`/gpt-5.5`, `openai/`, `a//b`, a
 * bare `:high`). Never throws, whatever the value.
 */
export function modelPinProblem(raw, field = "model") {
  if (typeof raw !== "string" || !pyStrip(raw)) return `invalid_model_pin: ${field} ${shownValue(raw)} must be a non-empty model name.`;
  const text = pyStrip(raw);
  let spelled;
  if (text.startsWith("auto:")) {
    const afterPrefix = text.slice(5);
    const at1 = afterPrefix.indexOf(":");
    const account = at1 < 0 ? "" : afterPrefix.slice(0, at1);
    const afterAccount = at1 < 0 ? "" : afterPrefix.slice(at1 + 1);
    const at2 = afterAccount.indexOf(":");
    const harness = at2 < 0 ? "" : afterAccount.slice(0, at2);
    const rest = at2 < 0 ? "" : afterAccount.slice(at2 + 1);
    if (at1 < 0 || at2 < 0 || !pyStrip(account) || !pyStrip(harness) || account.includes("/") || harness.includes("/")) {
      return `invalid_model_pin: ${field} ${shownValue(raw)} is a malformed auto bundle id; expected 'auto:<account>:<harness>:<model>'.`;
    }
    spelled = splitEffortSuffix(rest.split("#")[0].split("@")[0]).name;
  } else {
    spelled = splitEffortSuffix(text).name;
  }
  if (!spelled || spelled.split("/").some((seg) => !pyStrip(seg) || seg.split(":").some((c) => !pyStrip(c)))) {
    return `invalid_model_pin: ${field} ${shownValue(raw)} is malformed (empty prefix or model segment around '/'); write a bare model name (<model>) or <provider>/<model>.`;
  }
  return null;
}

/** `raw` stripped when it is a well-formed model pin, else throws `InvalidModelPin` (`model_resolution.check_model_pin`). */
export function checkModelPin(raw, field = "model") {
  const problem = modelPinProblem(raw, field);
  if (problem !== null) throw new InvalidModelPin(problem);
  return pyStrip(raw);
}

const isRow = (value) => value && typeof value === "object" && !Array.isArray(value);
const knownCache = new WeakMap();
/** The catalogue's row ids, and the same ids longest first (the family-prefix order); computed once per table, which no caller mutates. */
function knownNames(models) {
  const table = models || {};
  if (!knownCache.has(table)) {
    const known = new Set(Object.keys(table).filter((key) => isRow(table[key])));
    knownCache.set(table, { known, byLength: [...known].sort((x, y) => y.length - x.length || (x < y ? -1 : 1)) });
  }
  return knownCache.get(table);
}
const regexes = new Map();

function familyRegex(pattern) {
  // The patterns are Python's `re.search`; every one the catalogue ships is valid for both engines.
  if (!regexes.has(pattern)) regexes.set(pattern, new RegExp(pattern));
  return regexes.get(pattern);
}

/** A `provider_names` table that declares nothing: the table of a host catalogue that brings its own models and no table. */
export const NO_PROVIDER_NAMES = Object.freeze({ defaults: Object.freeze({}), rows: Object.freeze({}) });

/** The host whose list ids are `<preset>/<model>` (`gateway.go` `modelObject`) and whose preset ids `host_providers` maps. */
export const MAGPIE_HOST = "magpie";
/** The key of a host catalogue that names the host whose list ids its names are: a Symbol, so no JSON option sets it. */
export const LIST_HOST = Symbol("agentcompass.listHost");
const hostedOptions = new WeakMap();

/**
 * The plugin options as the Magpie adapter (the middleware, the hooks, the server) reads them: `options.catalog` marked with
 * `LIST_HOST` = `MAGPIE_HOST`, so every name read under it is a Magpie list id (`resolveListed`). The same object for the same
 * options. Cindy and a direct caller of the allocator never call this: under their catalogue no preset id is read.
 */
export function magpieOptions(options) {
  const given = options && typeof options === "object" ? options : {};
  if (!hostedOptions.has(given)) hostedOptions.set(given, { ...given, catalog: { ...(given.catalog || {}), [LIST_HOST]: MAGPIE_HOST } });
  return hostedOptions.get(given);
}

/**
 * The `provider_names` table a host's `options.catalog` brings, decided here only: its own `providerNames`; none
 * (`NO_PROVIDER_NAMES`) when it brings its own `models` without one, since the shipped table names rows such a catalogue need not
 * have; else the shipped table. Every reading of a name under that catalogue (`canonicalModel`, `servedModel`, `rowKey`,
 * `modelSpec`, `healthKey`, `catalogNameWarning`, `resolveModelKey`) reads what this returns. Under a catalogue the Magpie adapter
 * marked (`magpieOptions`) the table comes back with `host: "magpie"`, which `resolveListed` reads to take a list id's first
 * segment as a Magpie preset; under any other (Cindy, a direct caller of the allocator) it is the table itself, and no preset id is
 * ever read.
 */
export function providerNamesOf(catalog) {
  const given = catalog || {};
  let table = given.models ? NO_PROVIDER_NAMES : PROVIDER_NAMES;
  if (given.providerNames !== undefined && given.providerNames !== null) table = given.providerNames;
  return given[LIST_HOST] ? { ...table, host: given[LIST_HOST] } : table;
}

/** The tables a name is read with under a host's `options.catalog`: its models and aliases, the families, `providerNamesOf`. */
export function catalogTables(catalog) {
  const given = catalog || {};
  return { models: given.models || MODELS, aliases: given.aliases || MODEL_ALIASES, families: FAMILIES, providerNames: providerNamesOf(given) };
}

/** The `provider_names` table a resolution reads; a table without `defaults` and `rows` is refused, never read as declaring none. */
function providerNameTable(table) {
  if (!isRow(table) || !isRow(table.defaults) || !isRow(table.rows)) {
    throw new Error("the catalogue has no provider_names table: resolution needs { defaults: { name: declaration }, rows: { provider: { name: declaration } } }");
  }
  return table;
}

/**
 * `[[provider, name as that provider serves it]]` (`model_resolution.serving_providers`): the endpoints the caller knows serve the
 * name (`endpoints`: the Magpie preset a `modelsByProvider` list is for), each with the name as listed, since an id an endpoint
 * lists is in that endpoint's own namespace. With no endpoint known, the provider part of a `provider/name` id with the name after
 * it: a Magpie listing id is `<preset>/<model>` (`gateway.go` `modelObject`), a Cindy harness row `<provider>/<model>`. No
 * `:effort` suffix; duplicates dropped.
 */
export function servingProviders(rawModel, endpoints = []) {
  const { name } = splitEffortSuffix(rawModel);
  const out = (endpoints || []).filter(Boolean).map((p) => [String(p), name]);
  if (out.length === 0 && name.includes("/")) {
    const at = name.indexOf("/");
    out.push([name.slice(0, at), name.slice(at + 1)]);
  }
  const seen = new Set();
  return out.filter((pair) => {
    const key = JSON.stringify(pair);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

/** The spelling, then what follows each `/` in turn, ending at the last segment (`model_resolution.slash_suffixes`): `a/b/c`, `b/c`, `c`. */
export function slashSuffixes(spelling) {
  const parts = String(spelling).split("/");
  return parts.map((_, i) => parts.slice(i).join("/"));
}

const ownEntry = (table, key) => (Object.prototype.hasOwnProperty.call(table, key) ? table[key] : undefined);

/**
 * `[[provider, the spelling declared, declaration]]` of `table.rows` for the serving pairs (`model_resolution._declared_at`): each
 * provider's names are read in `slashSuffixes` order and the first declared wins. Providers and names are looked up lowercase.
 */
function declaredAt(pairs, table) {
  const out = [];
  for (const [p, n] of pairs) {
    const pid = p.toLowerCase();
    const rows = ownEntry(table.rows, pid);
    if (!isRow(rows)) continue;
    for (const candidate of slashSuffixes(n.toLowerCase())) {
      const entry = ownEntry(rows, candidate);
      if (isRow(entry)) {
        out.push([pid, candidate, entry]);
        break;
      }
    }
  }
  return out;
}

/**
 * `providers` with each preset id of `host` replaced by the models.dev catalog ids `host_providers[host]` maps it to
 * (`model_resolution.expand_host_providers`): an id the host's table does not hold stays itself; order kept, duplicates dropped.
 * Called only where a preset id of that host is held (a Magpie list id's first segment, `ctx.provider.id` in `onProvider`), never
 * inside the declaration lookup and never for another host.
 */
export function expandHostProviders(providers, host, table = PROVIDER_NAMES) {
  const hosts = isRow(table && table.host_providers) ? table.host_providers : {};
  const mapping = ownEntry(hosts, String(host || "").toLowerCase());
  const out = [];
  for (const p of providers || []) {
    if (!p) continue;
    const entry = isRow(mapping) ? ownEntry(mapping, String(p).toLowerCase()) : undefined;
    const targets = (isRow(entry) && Array.isArray(entry.providers) ? entry.providers : []).filter(Boolean);
    if (targets.length > 0) out.push(...targets.map(String));
    else out.push(String(p));
  }
  return [...new Set(out)];
}

/**
 * The `defaults` declaration of a lowercase spelling, read in `slashSuffixes` order (`model_resolution.default_for`): the full id,
 * then what follows each `/` in turn, then the last segment; the first declared wins, or `null`.
 */
export function defaultFor(spelling, table = PROVIDER_NAMES) {
  const { defaults } = providerNameTable(table);
  for (const candidate of slashSuffixes(spelling)) {
    const entry = ownEntry(defaults, candidate);
    if (isRow(entry)) return entry;
  }
  return null;
}

/** The `defaults` declaration of a name (lowercase, no `:effort`), or `null` (`model_resolution.maker_default`). */
export function makerDefault(rawModel, table = PROVIDER_NAMES) {
  return defaultFor(splitEffortSuffix(rawModel).name.toLowerCase(), table);
}

/**
 * `[[spelling, dash effort]]` (`model_resolution.undecorated`): the name (lowercase), then each vendor tag stripped in turn, then
 * the fully stripped name without a dash effort when it has one: the spellings `resolveModel` tries for a row, in its order.
 */
export function undecorated(rawName) {
  let name = rawName.toLowerCase();
  const out = [[name, null]];
  for (;;) {
    const stripped = name.replace(VENDOR_TAG_RE, "");
    if (stripped === name) break;
    name = stripped;
    out.push([name, null]);
  }
  const dashed = DASH_EFFORT_RE.exec(name);
  if (dashed) out.push([dashed[1], dashed[2]]);
  return out;
}

/**
 * The one model-name resolver (`model_resolution.resolve_model`): `{ key, source, effort, bare, provider }`.
 *
 * For each spelling of the name in turn (as given, each vendor tag stripped, a dash effort dropped): the serving providers'
 * declarations (`servingProviders`: one declared row is the key, source `provider`, the declaring provider in `provider`; a
 * declaration with no row gives its status, `retired` or `other_weights`, key `null`; providers that declare different rows give
 * `conflict`, key `null`, whatever their order), then the maker's `defaults` declaration of the full id before its last segment
 * (`defaultFor`, source `default`), then the row of that spelling (`exact`, `alias`). Names and provider ids are matched lowercase.
 * `source`: `exact` (the catalogue has this name), `alias` (another spelling of a row: provider prefix, case, date, `-latest`,
 * `-preview`, a vendor tag, an effort suffix or a listed alias), `family` (only a family pattern matched: `key` is the first
 * model of that family the catalogue knows, and the name has no scores), `unknown` (`key: null`, no scores). `effort` is what
 * the name itself asked for. `providers`: the endpoints the caller knows serve the name (`servingProviders`).
 */
export function resolveModel(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES, providers = []) {
  const { known, byLength } = knownNames(models);
  const table = aliases || {};
  const names = providerNameTable(providerNames);
  const exact = (candidate) => {
    const seen = new Set();
    let name = candidate;
    while (Object.prototype.hasOwnProperty.call(table, name) && !seen.has(name)) {
      seen.add(name);
      name = table[name];
    }
    return known.has(name) ? name : null;
  };
  const { name: raw, effort } = splitEffortSuffix(rawModel);
  let name = raw.split("/").pop().toLowerCase();
  const found = (key, source, namedEffort = null, provider = null, bare = null) => ({
    key,
    source,
    effort: effort || namedEffort,
    bare: bare === null ? name : bare,
    provider,
  });
  const byPair = (x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : x[1] < y[1] ? -1 : x[1] > y[1] ? 1 : 0);

  // The `found` of the declarations of one spelling (`served`: the serving pairs at this step), or `null`. `bare` is the spelling
  // reached, for a no-row pair the spelling its provider declares.
  const declaredRow = (full, spelling, served, dashEffort) => {
    const declared = declaredAt(served, names);
    if (new Set(declared.map(([, , d]) => JSON.stringify([d.model ?? null, d.status ?? null]))).size > 1) return found(null, "conflict", dashEffort, null, spelling);
    if (declared.length > 0) {
      const [by, servedName] = declared.map(([p, c]) => [p, c]).sort(byPair)[0];
      const d = declared.find(([p, c]) => p === by && c === servedName)[2];
      if (d.model == null) return found(null, d.status ?? null, dashEffort, by, servedName);
      if (!known.has(d.model)) throw new Error(`provider_names rows[${JSON.stringify(by)}] names row ${JSON.stringify(d.model)}, which the catalogue does not have`);
      return found(d.model, "provider", dashEffort, by, spelling);
    }
    const declaredDefault = defaultFor(full, names);
    if (declaredDefault) {
      if (!known.has(declaredDefault.model)) {
        throw new Error(`provider_names defaults[${JSON.stringify(full)}] names row ${JSON.stringify(declaredDefault.model ?? null)}, which the catalogue does not have`);
      }
      return found(declaredDefault.model, "default", dashEffort, null, spelling);
    }
    return null;
  };

  const pairs = servingProviders(raw, providers);
  const servedSteps = pairs.map(([, n]) => undecorated(n));
  const fullSteps = undecorated(raw); // the full id (owner part included), stripped as the last segment is
  const steps = undecorated(name);
  for (let step = 0; step < steps.length; step++) {
    const [spelling, dashEffort] = steps[step];
    if (dashEffort === null) name = spelling; // `bare`: the spelling reached so far (a dash effort is not stripped from it)
    const served = pairs.map(([p], i) => (step < servedSteps[i].length ? [p, servedSteps[i][step][0]] : null)).filter(Boolean);
    const full = step < fullSteps.length ? fullSteps[step][0] : spelling;
    const hit = declaredRow(full, spelling, served, dashEffort);
    if (hit !== null) return hit;
    if (step === 0) {
      for (const candidate of slashSuffixes(raw)) {
        const match = exact(candidate);
        if (match) return found(match, candidate === raw && match === raw ? "exact" : "alias");
        const lower = candidate.toLowerCase();
        if (lower !== candidate) {
          const alias = exact(lower);
          if (alias) return found(alias, "alias");
        }
      }
    } else {
      for (const candidate of slashSuffixes(full)) {
        const match = exact(candidate);
        if (match) return found(match, "alias", dashEffort, null, spelling);
      }
    }
  }
  const row = (families || []).find((f) => familyRegex(f.pattern).test(name));
  if (row) {
    const target = row.models.find((t) => known.has(t));
    return found(target || null, target ? "family" : "unknown");
  }
  for (const prefix of byLength) {
    // A delimiter keeps gpt-6.10 from matching gpt-6.1.
    if (name.startsWith(`${prefix}-`) || name.startsWith(`${prefix}:`)) {
      const match = exact(prefix);
      if (match) return found(match, "family");
    }
  }
  return found(null, "unknown");
}

/**
 * How a name with no endpoint given is read: by `resolveModel` as given, whose prefix is the serving provider (`servingProviders`)
 * and whose full id and each `/` suffix are read in one order (`slashSuffixes`), so `<preset>/<publisher>/<model>` reads its
 * `<publisher>/<model>` alias as `(model, [preset])` does. Under a table the Magpie adapter gave (`magpieOptions`, then
 * `providerNamesOf`) the name is a list id `<preset>/<model>`: when its first segment is a preset `host_providers.magpie` maps
 * (`opencode-zen` serves models.dev's `opencode`), the rest is the name those catalogs serve, read with them as its endpoints
 * (`expandHostProviders`). Under any other table (Cindy, a direct caller of the allocator) no preset id is read.
 */
export function resolveListed(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES, providers = []) {
  const text = String(rawModel ?? "").trim();
  const listed = (providers || []).filter(Boolean).length === 0 ? listedPreset(text, providerNames) : null;
  if (listed && (listed.served.length !== 1 || listed.served[0] !== listed.preset)) {
    return resolveModel(text.slice(listed.preset.length + 1), models, aliases, families, providerNames, listed.served);
  }
  return resolveModel(text, models, aliases, families, providerNames, providers);
}

/**
 * The preset a list id is listed under and the catalogs it serves, `{ preset, served }`, when the table is a host's view
 * (`providerNamesOf` of a catalogue `magpieOptions` marked) and the id has a `<preset>/` part; else `null`. Magpie's listing ids
 * are `<preset>/<model>`, so the first segment is the preset the model is offered on, as AgentCompass keeps a Magpie account's
 * preset ids beside the catalogs they expand to (`auto_bundles.endpoint_presets`).
 */
export function listedPreset(rawModel, providerNames = PROVIDER_NAMES) {
  const host = providerNames && providerNames.host;
  if (!host) return null;
  const text = String(rawModel ?? "").trim();
  const at = splitEffortSuffix(text).name.indexOf("/");
  if (at <= 0) return null;
  const preset = text.slice(0, at);
  return { preset, served: expandHostProviders([preset], host, providerNames) };
}

/** `<provider>/<bare>`, lowercase: a name with no row on its serving provider is that provider's own, never the same name elsewhere. */
function providerOwn(resolved) {
  return `${resolved.provider}/${resolved.bare}`.toLowerCase();
}

/**
 * The model a name is, as a value stored or compared that reads the same row again (`account_fleet.canonical` and `stored_form`,
 * and the spelling `auto_bundles.default_profile` gives a bundle): the row's key when the key reads back to that row; else the
 * name as given (a repository id whose row's own id now reads another row: `deepseek-ai/deepseek-v4-pro`), or, for a row a
 * serving provider declares, `<provider>/<leaf>`. `<provider>/<bare>` for a name with no row on its serving provider
 * (`PROVIDER_NAME_STATUSES`: the spelling that provider declares, `opencode/deepseek-v4-flash-high` is `opencode/deepseek-v4-flash`);
 * the name as given for a family guess or an unknown name, which is its own model.
 */
export function canonicalModel(rawModel, aliases = MODEL_ALIASES, models = MODELS, families = FAMILIES, providers = [], providerNames = PROVIDER_NAMES) {
  if (!rawModel || typeof rawModel !== "string") return "";
  const resolved = resolveListed(rawModel, models, aliases, families, providerNames, providers);
  if (PROVIDER_NAME_STATUSES.includes(resolved.source)) return providerOwn(resolved);
  if (!DIRECT_SOURCES.includes(resolved.source) || !resolved.key) return rawModel;
  if (resolveModel(resolved.key, models, aliases, families, providerNames).key === resolved.key) return resolved.key;
  // A declared row whose own id reads another row keeps the name qualified by its provider (`auto_bundles.default_profile`).
  return resolved.source === "provider" ? `${resolved.provider}/${modelLeaf(rawModel)}`.toLowerCase() : splitEffortSuffix(rawModel).name;
}

/**
 * The name a `modelsByProvider` entry is routed by on the preset that lists it (`auto_bundles.default_profile` with the endpoint):
 * the name as given, unless the preset's own `provider_names` declaration makes it another model than the name is with no provider
 * known; then `canonicalModel` of the name on that preset (`<preset>/<leaf>` for a name with no row there), which reads the same
 * declaration again wherever it is resolved. The effort the name asked for is kept.
 */
export function servedModel(rawModel, endpoints, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES) {
  const served = resolveModel(rawModel, models, aliases, families, providerNames, endpoints);
  // A preset's own model id, never a list id: read with no provider known, so no preset id is taken from its prefix.
  const plain = resolveModel(rawModel, models, aliases, families, providerNames);
  if (served.key !== null ? served.key === plain.key : served.source === plain.source) return rawModel;
  if (served.source !== "provider" && !PROVIDER_NAME_STATUSES.includes(served.source)) return rawModel;
  const own = canonicalModel(rawModel, aliases, models, families, endpoints, providerNames);
  if (own === rawModel) return rawModel;
  // The effort the name asked for, as `:effort` or `-effort` (`<provider>/<bare>` drops a dash effort from the name).
  return served.effort ? `${own}:${served.effort}` : own;
}

/** The leaf of a model name, without provider prefix or effort suffix. */
export function modelLeaf(rawModel) {
  return splitEffortSuffix(rawModel).name.split("/").pop();
}

/**
 * Which model a row runs: the resolved key for a row's own name or another spelling of it, its own leaf for a family guess or
 * an unknown name. A family guess folds to its target only for its estimated score; two rows are one model only when this
 * says so (`account_fleet.row_key`).
 */
export function rowKey(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES, providers = []) {
  const resolved = resolveListed(rawModel, models, aliases, families, providerNames, providers);
  if (PROVIDER_NAME_STATUSES.includes(resolved.source)) return providerOwn(resolved);
  return DIRECT_SOURCES.includes(resolved.source) ? resolved.key : modelLeaf(rawModel).toLowerCase();
}

/** The model's row for a name that is one (`exact`, `alias`); `{}` for a family guess or an unknown name: no scores, no price. */
export function modelSpec(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES) {
  const resolved = resolveListed(rawModel, models, aliases, families, providerNames);
  const row = DIRECT_SOURCES.includes(resolved.source) ? models[resolved.key] : null;
  return isRow(row) ? row : {};
}

/**
 * What a failure counts against. An `exact` or `alias` name is its row. A `family` or `unknown` name is only itself: a family
 * name is a different model from the row its pattern points at, so a preview that fails says nothing about that flagship.
 */
export function healthKey(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES) {
  if (!rawModel || typeof rawModel !== "string") return "";
  const resolved = resolveListed(rawModel, models, aliases, families, providerNames);
  if (DIRECT_SOURCES.includes(resolved.source)) return resolved.key;
  if (PROVIDER_NAME_STATUSES.includes(resolved.source)) return providerOwn(resolved);
  return modelLeaf(rawModel).toLowerCase();
}

/**
 * Whether a launch id runs at one effort only (`candidate_eval.has_fixed_effort`): `model:effort`, or `model-effort` where the
 * base is a calibrated row (`gemini-4-argon-high`). `-max` is also a size name (`qwen3-max`), so it splits only on a base the
 * catalogue knows.
 */
export function nameFixesEffort(rawModel, models = MODELS, aliases = MODEL_ALIASES) {
  const { name, effort } = splitEffortSuffix(rawModel);
  if (effort) return true;
  const match = /^(.+?)-(minimal|low|medium|high|xhigh|max)$/.exec(name);
  if (!match) return false;
  return match[2] !== "max" || match[1] in (models || {}) || match[1] in (aliases || {});
}

const MAX_NAME_IN_TEXT = 128;

/** Control characters as text, so a name can start no line of its own in a log. */
export function escapeControls(text) {
  return String(text).replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

/** A model name fit to put in a log or an error: under `routeAllModels` and in a pin, the request wrote it. */
export function safeName(name) {
  const text = String(name);
  return escapeControls(text.length > MAX_NAME_IN_TEXT ? `${text.slice(0, MAX_NAME_IN_TEXT)}...` : text);
}

/** Starts every `catalogNameWarning`, so a host can log each once rather than on every request. */
export const CATALOG_NAME_WARNING = "candidate name ";

/** Why a pool name is not routed on a row of its own, or `null` when it has one. */
export function catalogNameWarning(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES, providerNames = PROVIDER_NAMES) {
  const { key, source, provider } = resolveListed(rawModel, models, aliases, families, providerNames);
  if (DIRECT_SOURCES.includes(source)) return null;
  const { name } = splitEffortSuffix(rawModel);
  if (PROVIDER_NAME_STATUSES.includes(source)) {
    const why = source === "retired" ? "no longer serves this name (retired)" : "serves this name as weights the public data has no row for (other_weights)";
    return `${CATALOG_NAME_WARNING}${safeName(name)} has no row: ${safeName(provider)} ${why}, by provider_names: no scores, so it leaves automatic routing (name it to dispatch it)`;
  }
  if (source === "conflict") {
    return `${CATALOG_NAME_WARNING}${safeName(name)} has no row: its serving providers declare different rows (provider_names): no scores, so it leaves automatic routing (name it to dispatch it)`;
  }
  // A family match names the series the name belongs to; its scores are that row's, not this name's, so the name has none.
  const series = source === "family" ? `it matches the ${key} series but has no row of its own, so it has ` : "";
  return `${CATALOG_NAME_WARNING}${safeName(name)} is not in the catalog: ${series}no scores: a demanded category is a data error, so it leaves automatic routing (name it to dispatch it)`;
}

/**
 * `round(value, digits)` as Python does it: the double's exact value decides, and an exact tie goes to the even digit.
 * `Math.round(x * 1000)` rounds the product instead, and 0.7625 lands on the other side of it.
 */
export function pyRound(value, digits) {
  const number = Number(value);
  const scaled = Math.abs(number) * 10 ** digits;
  if (Math.abs(scaled - Math.floor(scaled) - 0.5) > 1e-6) return Number(number.toFixed(digits)) + 0;
  const exact = number.toFixed(digits + 60);
  const cut = exact.indexOf(".") + 1 + digits;
  if (!/^50*$/.test(exact.slice(cut)) || Number(exact[cut - 1]) % 2 === 1) return Number(number.toFixed(digits)) + 0;
  return Number(exact.slice(0, cut)) + 0;
}
