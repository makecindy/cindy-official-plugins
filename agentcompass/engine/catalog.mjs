/** A `:effort` suffix names an effort, not a vendor tag: `claude-opus-5-5:medium` asks for Medium. */
export const EFFORT_SUFFIXES = ["none", "minimal", "default", "low", "medium", "high", "xhigh", "max", "ultra"];
const COLON_EFFORT_RE = new RegExp(`^(.+):(${EFFORT_SUFFIXES.join("|")})$`, "i");
const DASH_EFFORT_RE = new RegExp(`^(.+)-(${EFFORT_SUFFIXES.join("|")})$`);
const VENDOR_TAG_RE = /(?:@\d{8}|-\d{8}|-\d{4}-\d{2}-\d{2}|:\w+|\[\w+\]|-(?:latest|preview))$/;
/** How a name reached its row: `family` and `unknown` carry no scores of their own. */
export const DIRECT_SOURCES = ["exact", "alias"];

/** `("claude-opus-5-5", "medium")` for `claude-opus-5-5:medium`; `(raw, null)` without an effort suffix. */
export function splitEffortSuffix(rawModel) {
  const name = String(rawModel ?? "").trim();
  const match = COLON_EFFORT_RE.exec(name);
  return match ? { name: match[1], effort: match[2].toLowerCase() } : { name, effort: null };
}

const isRow = (value) => value && typeof value === "object" && !Array.isArray(value);
const knownNames = (models) => new Set(Object.keys(models || {}).filter((key) => isRow(models[key])));
const regexes = new Map();

function familyRegex(pattern) {
  // The patterns are Python's `re.search`; every one the catalogue ships is valid for both engines.
  if (!regexes.has(pattern)) regexes.set(pattern, new RegExp(pattern));
  return regexes.get(pattern);
}

/**
 * The one model-name resolver (`model_resolution.resolve_model`): `{ key, source, effort, bare }`.
 * `source`: `exact` (the catalogue has this name), `alias` (another spelling of a row: provider prefix, case, date, `-latest`,
 * `-preview`, a vendor tag, an effort suffix or a listed alias), `family` (a different model of a known family, scored as an
 * estimate of its target), `unknown` (`key: null`, no scores). `effort` is what the name itself asked for.
 */
export function resolveModel(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES) {
  const known = knownNames(models);
  const table = aliases || {};
  const exact = (candidate) => {
    const seen = new Set();
    let name = candidate;
    while (Object.prototype.hasOwnProperty.call(table, name) && !seen.has(name)) {
      seen.add(name);
      name = table[name];
    }
    return known.has(name) ? name : null;
  };
  const { name: raw, effort } = splitEffortSuffix(rawModel);
  let name = raw.split("/").pop().toLowerCase();
  const found = (key, source, namedEffort = null) => ({ key, source, effort: effort || namedEffort, bare: name });

  let match = exact(raw);
  if (match) return found(match, match === raw ? "exact" : "alias");
  for (const candidate of [raw.split("/").pop(), raw.toLowerCase(), name]) {
    match = exact(candidate);
    if (match) return found(match, "alias");
  }
  for (;;) {
    const stripped = name.replace(VENDOR_TAG_RE, "");
    if (stripped === name) break;
    name = stripped;
    match = exact(name);
    if (match) return found(match, "alias");
  }
  const dashed = DASH_EFFORT_RE.exec(name);
  if (dashed) {
    match = exact(dashed[1]);
    if (match) return found(match, "alias", dashed[2]);
  }
  const row = (families || []).find((f) => familyRegex(f.pattern).test(name));
  if (row) {
    const target = row.models.find((t) => known.has(t));
    return found(target || null, target ? "family" : "unknown");
  }
  for (const prefix of [...known].sort((a, b) => b.length - a.length || (a < b ? -1 : 1))) {
    // A delimiter keeps gpt-6.10 from matching gpt-6.1.
    if (name.startsWith(`${prefix}-`) || name.startsWith(`${prefix}:`)) {
      match = exact(prefix);
      if (match) return found(match, "family");
    }
  }
  return found(null, "unknown");
}

/** The key of `rawModel` when it is a model (`exact`, `alias`); the name as given for a family guess or an unknown name, which is its own model. */
export function canonicalModel(rawModel, aliases = MODEL_ALIASES, models = MODELS, families = FAMILIES) {
  if (!rawModel || typeof rawModel !== "string") return "";
  const resolved = resolveModel(rawModel, models, aliases, families);
  return (DIRECT_SOURCES.includes(resolved.source) && resolved.key) || rawModel;
}

/** The leaf of a model name, without provider prefix or effort suffix. */
export function modelLeaf(rawModel) {
  return splitEffortSuffix(rawModel).name.split("/").pop();
}

/**
 * Which model a row runs: the resolved key for a row's own name or another spelling of it, its own leaf for a family guess or
 * an unknown name. A family guess folds to its target only for its estimated score; two rows are one model only when this
 * says so (`account_fleet.row_key`).
 */
export function rowKey(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES) {
  const resolved = resolveModel(rawModel, models, aliases, families);
  return DIRECT_SOURCES.includes(resolved.source) ? resolved.key : modelLeaf(rawModel).toLowerCase();
}

/** The model's row for a name that is one (`exact`, `alias`); `{}` for a family guess or an unknown name: no scores, no price. */
export function modelSpec(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES) {
  const resolved = resolveModel(rawModel, models, aliases, families);
  const row = DIRECT_SOURCES.includes(resolved.source) ? models[resolved.key] : null;
  return isRow(row) ? row : {};
}

/**
 * What a failure counts against. An `exact` or `alias` name is its row. A `family` or `unknown` name is only itself: a family
 * row is an estimate of its target, so a preview that fails says nothing about the flagship it was placed on.
 */
export function healthKey(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES) {
  if (!rawModel || typeof rawModel !== "string") return "";
  const { key, source } = resolveModel(rawModel, models, aliases, families);
  if (DIRECT_SOURCES.includes(source)) return key;
  return modelLeaf(rawModel).toLowerCase();
}

/**
 * Whether a launch id runs at one effort only (`candidate_eval.has_fixed_effort`): `model:effort`, or `model-effort` where the
 * base is a calibrated row (`gemini-4-argon-high`). `-max` is also a size name (`qwen3-max`), so it splits only on a base the
 * catalogue knows.
 */
export function nameFixesEffort(rawModel, models = MODELS, aliases = MODEL_ALIASES) {
  const { name, effort } = splitEffortSuffix(rawModel);
  if (effort) return true;
  const match = /^(.+?)-(minimal|low|medium|high|xhigh|max)$/.exec(name);
  if (!match) return false;
  return match[2] !== "max" || match[1] in (models || {}) || match[1] in (aliases || {});
}

const MAX_NAME_IN_TEXT = 128;

/** Control characters as text, so a name can start no line of its own in a log. */
export function escapeControls(text) {
  return String(text).replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

/** A model name fit to put in a log or an error: under `routeAllModels` and in a pin, the request wrote it. */
export function safeName(name) {
  const text = String(name);
  return escapeControls(text.length > MAX_NAME_IN_TEXT ? `${text.slice(0, MAX_NAME_IN_TEXT)}...` : text);
}

/** Starts every `catalogNameWarning`, so a host can log each once rather than on every request. */
export const CATALOG_NAME_WARNING = "candidate name ";

/** Why a pool name is not routed on a row of its own, or `null` when it has one. */
export function catalogNameWarning(rawModel, models = MODELS, aliases = MODEL_ALIASES, families = FAMILIES) {
  const { key, source } = resolveModel(rawModel, models, aliases, families);
  if (DIRECT_SOURCES.includes(source)) return null;
  const { name } = splitEffortSuffix(rawModel);
  const scored =
    source === "family"
      ? `scored as an estimate of ${key} (its same-series row)`
      : "no scores: a demanded category is a data error, so it leaves automatic routing (name it to dispatch it)";
  return `${CATALOG_NAME_WARNING}${safeName(name)} is not in the catalog: ${scored}`;
}

/**
 * `round(value, digits)` as Python does it: the double's exact value decides, and an exact tie goes to the even digit.
 * `Math.round(x * 1000)` rounds the product instead, and 0.7625 lands on the other side of it.
 */
export function pyRound(value, digits) {
  const number = Number(value);
  const scaled = Math.abs(number) * 10 ** digits;
  if (Math.abs(scaled - Math.floor(scaled) - 0.5) > 1e-6) return Number(number.toFixed(digits)) + 0;
  const exact = number.toFixed(digits + 60);
  const cut = exact.indexOf(".") + 1 + digits;
  if (!/^50*$/.test(exact.slice(cut)) || Number(exact[cut - 1]) % 2 === 1) return Number(number.toFixed(digits)) + 0;
  return Number(exact.slice(0, cut)) + 0;
}
